"""Build src/art.ts from the transparent role cutouts in art/cut_*.png.

The cutouts come from the role sheets (art/sheet.png, art/sheet2.png for the Troublemaker)
via tools/cutout.py. Run from the repository root:  python3 tools/encode_art.py
"""
import base64, io
from PIL import Image

ROLES = ['werewolf', 'mysticwolf', 'minion', 'mason', 'seer', 'seer2', 'apprenticeseer', 'robber',
         'witch', 'troublemaker', 'gremlin', 'drunk', 'insomniac', 'hunter', 'tanner', 'villager', 'alphawolf']
SCALE = {'troublemaker': 2.4, 'alphawolf': 1.2}   # the second sheet is lower resolution

lines = ['// Generated by tools/encode_art.py from art/cut_*.png. Transparent cutouts, WebP.',
         'export const ART: Record<string, string> = {']
for name in ROLES:
    im = Image.open(f'art/cut_{name}.png').convert('RGBA')
    k = SCALE.get(name, 1.5)
    im = im.resize((int(im.width * k), int(im.height * k)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=86, method=6)
    lines.append(f'  {name}: "data:image/webp;base64,{base64.b64encode(buf.getvalue()).decode()}",')
lines.append('};')
open('src/art.ts', 'w').write('\n'.join(lines) + '\n')
print('wrote src/art.ts')
